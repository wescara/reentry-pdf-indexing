def validate_config(require_credentials: bool = True):
    """Ensure required configuration is present before proceeding."""
    missing = []
    if require_credentials:
        if not KNACK_API_KEY:
            missing.append("KNACK_API_KEY")
        if not KNACK_APP_ID:
            missing.append("KNACK_APP_ID")
    if not REENTRY_TABLE_ID:
        missing.append("REENTRY_TABLE_ID")
    if not REENTRY_DOCS_TABLE_ID:
        missing.append("REENTRY_DOCS_TABLE_ID")
    
    if missing:
        raise RuntimeError(
            "Missing required environment variables: "
            + ", ".join(missing)
            + "\n\nFix:\n"
            "- Ensure your .env file (in project root) contains these keys with values.\n"
        )


def knack_request(
    method: str,
    endpoint: str,
    data: Optional[Dict] = None,
    timeout: int = DEFAULT_TIMEOUT,
) -> Dict:
    """Make authenticated request to Knack API."""
    url = f"{KNACK_API_BASE}{endpoint}"
    headers = {
        "X-Knack-Application-Id": KNACK_APP_ID,
        "X-Knack-REST-API-Key": KNACK_API_KEY,
        "Content-Type": "application/json",
    }
    
    try:
        if method == "GET":
            response = requests.get(url, headers=headers, timeout=timeout)
        elif method == "POST":
            response = requests.post(url, json=data, headers=headers, timeout=timeout)
        elif method == "DELETE":
            response = requests.delete(url, headers=headers, timeout=timeout)
        else:
            raise ValueError(f"Unsupported HTTP method: {method}")
        
        if response.status_code >= 400:
            try:
                error_detail = response.json()
            except:
                error_detail = response.text[:500]
            logger.error(f"Knack API {response.status_code}: {error_detail}")
        
        response.raise_for_status()
        return response.json() if response.text else {}
    except requests.exceptions.RequestException as e:
        logger.error(f"Knack API error: {e}")
        raise


def get_reentry_categories() -> Dict[str, str]:
    """
    Fetch Reentry table records and build category_key mapping.
    Returns: {"category_name": "category_key", ...}
    """
    logger.info("Fetching Reentry table records from Knack...")
    
    endpoint = f"/tables/{REENTRY_TABLE_ID}/records"
    response = knack_request("GET", endpoint)
    
    records = response.get("records", [])
    category_map = {}
    
    for record in records:
        # Assumes URLDescription field has the category name
        # CHANGE FIELD IDs TO MATCH YOUR KNACK TABLE STRUCTURE
        category_name = record.get("fields", {}).get("f_2")  # Adjust f_2 to your URLDescription field ID
        category_key = record.get("fields", {}).get(CATEGORY_KEY_FIELD)
        
        if category_name and category_key:
            category_map[category_name] = category_key
            logger.debug(f"  {category_name} → {category_key}")
    
    logger.info(f"Loaded {len(category_map)} categories from Reentry table")
    return category_map


def read_search_index(limit: Optional[int] = None) -> List[Dict]:
    """Read search_index_full.csv and prepare records for upload."""
    if not os.path.exists(SEARCH_INDEX_FULL):
        raise FileNotFoundError(f"{SEARCH_INDEX_FULL} not found. Run build_search_index.py first.")
    
    logger.info(f"Reading {SEARCH_INDEX_FULL}...")
    df = pd.read_csv(SEARCH_INDEX_FULL)
    
    if limit:
        df = df.head(limit)
        logger.info(f"Limited to first {limit} records for testing")
    
    logger.info(f"Loaded {len(df)} PDF records")
    return df.to_dict("records")


def get_reentry_category_map() -> Dict[str, str]:
    """Fetch all Reentry records and build name -> ID mapping."""
    logger.info("Fetching Reentry categories from Knack...")
    
    # Use format=json to ensure fields are returned in list endpoint
    endpoint = f"/objects/{REENTRY_TABLE_ID}/records?rows_per_page=100&format=json"
    response = knack_request("GET", endpoint)
    records = response.get("records", [])
    
    # Build mapping: category_name -> record_id
    category_map = {}
    for record in records:
        # field_162 contains the category name (URLDescription)
        name = record.get("field_162")
        record_id = record.get("id")
        if name and record_id:
            category_map[name] = record_id
            logger.info(f"  Found: {name} -> {record_id}")
    
    logger.info(f"Loaded {len(category_map)} categories")
    return category_map


def build_knack_records(
    pdf_records: List[Dict],
    category_map: Dict[str, str],
) -> List[Dict]:
    """
    Transform PDF records into Knack Reentry Documents format.
    Sends category name as text (field_175 is now Short Text, not Link).
    Splits full text across 5 fields (field_169, field_177-180) @ ~15k chars each.
    """
    logger.info("Building Knack records...")
    
    knack_records = []
    missing_categories = set()
    
    # Text splitting logic
    TEXT_CHUNK_SIZE = 15000
    TEXT_FIELDS = [
        FIELD_FULL_TEXT,
        FIELD_FULL_TEXT_2,
        FIELD_FULL_TEXT_3,
        FIELD_FULL_TEXT_4,
        FIELD_FULL_TEXT_5,
    ]
    
    for pdf in pdf_records:
        category = pdf.get("parent_category", "")
        
        # Verify category exists in Reentry table
        if category not in category_map:
            missing_categories.add(category)
            logger.warning(f"Category '{category}' not found in Reentry table")
            continue  # Skip this record if category doesn't exist
        
        full_text = pdf.get("extracted_text", "")
        
        # Split full text across multiple fields (15k chars each)
        text_chunks = []
        for i in range(0, len(full_text), TEXT_CHUNK_SIZE):
            text_chunks.append(full_text[i:i+TEXT_CHUNK_SIZE])
        
        # Build Knack record - only include non-empty fields
        knack_record = {
            FIELD_FILENAME: pdf.get("filename"),
            FIELD_CATEGORY: category,  # Category as text (field_175 is Short Text)
            # Skip FIELD_TEXT_PREVIEW since it has unique constraint - we have full text anyway
            FIELD_EXTRACTION_METHOD: pdf.get("extraction_method", "pdfplumber"),
            FIELD_FILE_SIZE_MB: float(pdf.get("file_size_mb", 0)),
            FIELD_PAGE_COUNT: int(pdf.get("page_count", 0)),
        }
        
        # Add OneDrive URL only if present
        web_url = pdf.get("web_url", "").strip()
        if web_url:
            knack_record[FIELD_ONEDRIVE_URL] = web_url
        
        # Distribute text chunks across text fields (only non-empty chunks)
        for idx, field_id in enumerate(TEXT_FIELDS):
            if idx < len(text_chunks) and text_chunks[idx].strip():
                knack_record[field_id] = text_chunks[idx]
            # Don't include empty text fields - let Knack leave them null
        
        knack_records.append(knack_record)
    
    if missing_categories:
        logger.warning(f"Skipped records for missing categories: {missing_categories}")
    
    logger.info(f"Built {len(knack_records)} Knack records from {len(pdf_records)} PDFs")
    return knack_records


def truncate_reentry_documents():
    """Delete all records from Reentry Documents table (truncate)."""
    logger.info(f"Truncating {REENTRY_DOCS_TABLE_ID}...")
    
    # Fetch ALL records (use rows_per_page=1000 to get all in one request)
    endpoint = f"/objects/{REENTRY_DOCS_TABLE_ID}/records?rows_per_page=1000"
    response = knack_request("GET", endpoint)
    records = response.get("records", [])
    
    logger.info(f"Found {len(records)} records to delete")
    
    # Delete each record
    deleted = 0
    for record in records:
        record_id = record.get("id")
        delete_endpoint = f"/objects/{REENTRY_DOCS_TABLE_ID}/records/{record_id}"
        try:
            knack_request("DELETE", delete_endpoint)
            deleted += 1
        except Exception as e:
            logger.warning(f"Failed to delete record {record_id}: {e}")
    
    logger.info(f"Deleted {deleted} existing records")


def load_reentry_documents(knack_records: List[Dict]):
    """Insert all Reentry Documents records into Knack."""
    logger.info(f"Loading {len(knack_records)} records to {REENTRY_DOCS_TABLE_ID}...")  
    
    endpoint = f"/objects/{REENTRY_DOCS_TABLE_ID}/records"
    created = 0
    failed = 0
    
    for idx, record in enumerate(knack_records, start=1):
        try:
            # Get filename from record (field_166)
            filename = record.get(FIELD_FILENAME, 'unknown')
            print(f"({idx}/{len(knack_records)}) Creating: {filename}")
            knack_request("POST", endpoint, data=record)
            created += 1
        except Exception as e:
            logger.warning(f"Failed to create record {idx}: {e}")
            failed += 1
    
    logger.info(f"Created {created} records ({failed} failed)")
    return created, failed


def main(test_limit: Optional[int] = None):
    """Main workflow: read PDFs, truncate and load."""
    start_time = time.time()
    
    try:
        validate_config(require_credentials=True)
        
        # Step 1: Fetch category mappings from Reentry table
        category_map = get_reentry_category_map()
        
        # Step 2: Read PDF data
        pdf_records = read_search_index(limit=test_limit)
        
        # Step 3: Transform to Knack format
        knack_records = build_knack_records(pdf_records, category_map)
        
        # Step 4: Truncate existing records
        truncate_reentry_documents()
        
        # Step 5: Load new records
        created, failed = load_reentry_documents(knack_records)
        
        # Summary
        elapsed = time.time() - start_time
        minutes = int(elapsed) // 60
        seconds = int(elapsed) % 60
        
        logger.info("=" * 70)
        logger.info(f"✅ Upload completed successfully!")
        logger.info(f"   Records created: {created}")
        logger.info(f"   Records failed: {failed}")
        logger.info(f"   Processing time: {minutes}m {seconds}s")
        logger.info("=" * 70)
        
    except Exception as e:
        logger.error(f"Fatal error: {e}")
        import traceback
        traceback.print_exc()
        sys.exit(1)


if __name__ == "__main__":
    # Run full pipeline with all records
    main()
