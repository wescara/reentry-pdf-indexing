"""
Knack Uploader: Push PDF records to Knack database.

Features:
- Reads Reentry table from Knack to get category keys
- Reads search_index_full.csv for PDF data
- Creates Reentry Documents records linked to categories
- Truncate and load (replaces all records weekly)
- Error handling and detailed logging
- Processing time reporting
- Works with both OneDrive and SharePoint URLs

Prereqs:
- Knack API credentials in .env (KNACK_API_KEY, KNACK_APP_ID)
- pip install requests python-dotenv pandas

SharePoint Migration:
- Set USE_SHAREPOINT=true in .env to use SharePoint URLs instead of OneDrive
- Both use the same field (FIELD_ONEDRIVE_URL) for file links
- SharePoint URLs will automatically be used when data is generated by sharepoint_graph_client.py
"""

